import { copyFile, mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { type AddressInfo, createServer, type Socket } from 'node:net';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { sql } from 'drizzle-orm';
import { afterEach, describe, expect, it } from 'vitest';
import drizzleConfig from '../drizzle.config.ts';
import { CONNECT_TIMEOUT_MS, type DbHandle, openPglite, openPostgres } from '../src/db/client.ts';
import { MIGRATIONS_FOLDER, runMigrations } from '../src/db/migrate.ts';
import { createTestDb, queryRows } from './support/db.ts';
import { captureLog } from './support/log.ts';
import { createPostgresTestDb, databaseExists, TEST_DATABASE_URL } from './support/postgres.ts';
import { PGLITE_TIMEOUT } from './support/timeouts.ts';

/** `apps/server`, the folder drizzle-kit resolves `drizzle.config.ts` paths against. */
const SERVER_ROOT = new URL('../', import.meta.url);

/** The probe migration (one `CREATE TABLE "probe"`), generated by drizzle-kit. */
const PROBE_FOLDER = fileURLToPath(new URL('./fixtures/migrations', import.meta.url));

async function count(h: DbHandle, query: ReturnType<typeof sql>): Promise<number> {
  return Number((await queryRows(h, query))[0]?.n);
}

const advisoryLocks = (h: DbHandle) => count(h, sql`select count(*)::int as n from pg_locks where locktype = 'advisory'`);
const migrationRows = (h: DbHandle) => count(h, sql`select count(*)::int as n from drizzle.__drizzle_migrations`);
const probeTables = (h: DbHandle) =>
  count(h, sql`select count(*)::int as n from information_schema.tables where table_schema = 'public' and table_name = 'probe'`);

/** Handles and folders a test opened, closed or removed after it whatever the outcome. */
const cleanup: (() => Promise<unknown>)[] = [];
afterEach(async () => {
  for (const step of cleanup.splice(0).reverse()) await step();
});

async function pglite(): Promise<DbHandle> {
  const h = await openPglite();
  cleanup.push(() => h.close());
  return h;
}

async function tempFolder(): Promise<string> {
  const dir = await mkdtemp(join(tmpdir(), 'ua-migrations-'));
  cleanup.push(() => rm(dir, { recursive: true, force: true }));
  return dir;
}

/** A copy of the probe fixture whose SQL has a syntax error. */
const BROKEN_SQL = 'CREATE TABL "probe" (\n\t"id" integer PRIMARY KEY NOT NULL\n);\n';
async function brokenProbeFolder(): Promise<string> {
  const dir = await tempFolder();
  await mkdir(join(dir, 'meta'));
  await copyFile(join(PROBE_FOLDER, 'meta', '_journal.json'), join(dir, 'meta', '_journal.json'));
  await writeFile(join(dir, '0000_probe.sql'), BROKEN_SQL);
  return dir;
}

describe('client', { timeout: PGLITE_TIMEOUT }, () => {
  it('test_pglite_select_one', async () => {
    const h = await pglite();
    expect(h.kind).toBe('pglite');
    expect(await queryRows(h, sql`select 1 as one`)).toEqual([{ one: 1 }]);
  });

  it('test_create_test_db_and_close', async () => {
    // A wrong folder would pass silently: with no journal there, runMigrations is a quiet no-op. So createTestDb's
    // default must be the folder db:generate writes to.
    expect(MIGRATIONS_FOLDER).toBe(fileURLToPath(new URL(String(drizzleConfig.out), SERVER_ROOT)));
    const h = await createTestDb();
    expect(h.kind).toBe('pglite');
    expect(await queryRows(h, sql`select 1 as one`)).toEqual([{ one: 1 }]);
    await expect(h.close()).resolves.toBeUndefined();
  });

  it('test_postgres_connect_times_out', async () => {
    // A server that accepts the connection and never answers, like a database behind a dropped route.
    const sockets = new Set<Socket>();
    const silent = createServer((socket) => sockets.add(socket));
    await new Promise<void>((resolve) => silent.listen(0, '127.0.0.1', resolve));
    cleanup.push(
      () =>
        new Promise((resolve) => {
          for (const socket of sockets) socket.destroy();
          silent.close(resolve);
        }),
    );
    const { port } = silent.address() as AddressInfo;

    const h = openPostgres(`postgres://ua@127.0.0.1:${port}/ua`, undefined, { connectTimeoutMs: 200 });
    cleanup.push(() => h.close());
    const started = performance.now();
    await expect(h.db.execute(sql`select 1`)).rejects.toThrow();
    expect(performance.now() - started).toBeLessThan(5_000);
    expect(sockets.size).toBe(1);

    // Without the option, the pool gets the server's default.
    const byDefault = openPostgres(`postgres://ua@127.0.0.1:${port}/ua`);
    cleanup.push(() => byDefault.close());
    expect(byDefault.kind === 'postgres' && byDefault.pool.options.connectionTimeoutMillis).toBe(CONNECT_TIMEOUT_MS);
  });

  it('test_create_test_db_applies_migrations', async () => {
    const h = await createTestDb(PROBE_FOLDER);
    cleanup.push(() => h.close());
    expect(await probeTables(h)).toBe(1);
    expect(await migrationRows(h)).toBe(1);
  });
});

describe('migrations', { timeout: PGLITE_TIMEOUT }, () => {
  it('test_migrations_apply_once', async () => {
    const h = await pglite();
    const { log, events } = captureLog();
    await expect(runMigrations(h, { migrationsFolder: PROBE_FOLDER, log })).resolves.toEqual({ applied: true });
    expect(await probeTables(h)).toBe(1);
    await expect(runMigrations(h, { migrationsFolder: PROBE_FOLDER, log })).resolves.toEqual({ applied: true });
    expect(await migrationRows(h)).toBe(1);
    expect(events().map((e) => e.event)).toEqual([
      'db.migrations.start',
      'db.migrations.done',
      'db.migrations.start',
      'db.migrations.done',
    ]);
    expect(events()[1]?.ms).toEqual(expect.any(Number));
  });

  it('test_migrations_release_lock', async () => {
    const h = await pglite();
    await runMigrations(h, { migrationsFolder: PROBE_FOLDER, log: captureLog().log });
    expect(await advisoryLocks(h)).toBe(0);
  });

  it('test_migrations_failure_releases_lock_and_logs_no_sql', async () => {
    const h = await pglite();
    const { log, lines, events } = captureLog();
    await expect(runMigrations(h, { migrationsFolder: await brokenProbeFolder(), log })).rejects.toThrow();
    expect(await advisoryLocks(h)).toBe(0);
    expect(await probeTables(h)).toBe(0);

    const failed = events().find((e) => e.event === 'db.migrations.failed');
    expect(failed?.level).toBe('error');
    expect(failed?.err_name).toEqual(expect.any(String));
    const output = lines.join('');
    for (const fragment of ['CREATE', 'TABL', 'probe', 'PRIMARY KEY', 'integer']) expect(output).not.toContain(fragment);
  });

  it('test_migrations_missing_journal_is_noop', async () => {
    const h = await pglite();
    const { log, events } = captureLog();
    await expect(runMigrations(h, { migrationsFolder: await tempFolder(), log })).resolves.toEqual({ applied: false });
    expect(events().map((e) => e.event)).toEqual(['db.migrations.none']);
    expect(await advisoryLocks(h)).toBe(0);
  });
});

describe.skipIf(!TEST_DATABASE_URL)('postgres', { timeout: PGLITE_TIMEOUT }, () => {
  it('test_postgres_test_dbs_are_separate_and_dropped', async () => {
    const [one, two] = await Promise.all([createPostgresTestDb(), createPostgresTestDb()]);
    cleanup.push(
      () => one.drop(),
      () => two.drop(),
    );
    expect(one.name).toMatch(/^ua_test_[0-9a-f]{12}$/);
    expect(one.name).not.toBe(two.name);

    const [a, b] = [openPostgres(one.url), openPostgres(two.url)];
    cleanup.push(
      () => a.close(),
      () => b.close(),
    );
    expect(await queryRows(a, sql`select current_database() as name`)).toEqual([{ name: one.name }]);
    await a.db.execute(sql`create table probe (id integer)`);
    expect(await probeTables(a)).toBe(1);
    expect(await probeTables(b)).toBe(0);

    // drop() ends the connections still open to it, and a second call does nothing.
    expect(await databaseExists(one.name)).toBe(true);
    await one.drop();
    await expect(one.drop()).resolves.toBeUndefined();
    expect(await databaseExists(one.name)).toBe(false);
  });

  it('test_concurrent_migrations_on_postgres', async () => {
    const fresh = await createPostgresTestDb('ua_migrate');
    cleanup.push(() => fresh.drop());
    const [a, b] = [openPostgres(fresh.url), openPostgres(fresh.url)];
    cleanup.push(
      () => a.close(),
      () => b.close(),
    );

    const { log } = captureLog();
    const results = await Promise.all([
      runMigrations(a, { migrationsFolder: PROBE_FOLDER, log }),
      runMigrations(b, { migrationsFolder: PROBE_FOLDER, log }),
    ]);
    expect(results).toEqual([{ applied: true }, { applied: true }]);

    const journal = JSON.parse(await readFile(join(PROBE_FOLDER, 'meta', '_journal.json'), 'utf8')) as { entries: unknown[] };
    expect(await migrationRows(a)).toBe(journal.entries.length);
    expect(await probeTables(a)).toBe(1);
  });
});
